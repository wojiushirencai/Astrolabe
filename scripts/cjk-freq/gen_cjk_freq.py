#!/usr/bin/env python3
"""Regenerate crates/astrolabe-core/src/text/cjk_freq.rs from our own counts.

The tables are the top-N characters by frequency in a plain-text sample of
Wikipedia, counted here; no third-party frequency table is used or copied.
Only the character sets end up in the source file (no text).

  gen_cjk_freq.py fetch OUTDIR   # download the sample (stdlib only, ~15 min)
  gen_cjk_freq.py gen OUTDIR     # count and write cjk_freq.rs

Sample per locale (Oct 2026 run): ~400 full articles linked from a few
computing seed pages (source comments are technical text) plus random
article intros; zh is fetched twice with the zh-cn / zh-tw variants.
Characters that are not encodable in the locale's legacy encoding are
skipped. Re-running gives slightly different tables as Wikipedia changes.
"""
import collections, glob, json, os, random, sys, time, urllib.parse, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEST = os.path.join(ROOT, "crates/astrolabe-core/src/text/cjk_freq.rs")
UA = {"User-Agent": "astrolabe-cjkfreq/0.1 (character statistics)"}
LOCALES = {  # key: (wiki, variant, seed pages)
    "hans": ("zh", "zh-cn", ["计算机科学", "编程语言", "软件", "操作系统", "计算机网络", "数据库"]),
    "hant": ("zh", "zh-tw", ["计算机科学", "编程语言", "软件", "操作系统", "计算机网络", "数据库"]),
    "ja": ("ja", None, ["計算機科学", "プログラミング言語", "ソフトウェア",
                        "オペレーティングシステム", "コンピュータネットワーク", "データベース"]),
    "ko": ("ko", None, ["컴퓨터 과학", "프로그래밍 언어", "소프트웨어", "운영체제",
                        "컴퓨터 네트워크", "데이터베이스"]),
}
# name, sample key, Han or Hangul, N, legacy codec
SPEC = [("ZH_HANS", "hans", "han", 1000, "gb2312"), ("ZH_HANT", "hant", "han", 1000, "big5"),
        ("JA_KANJI", "ja", "han", 800, "cp932"), ("KO_HANGUL", "ko", "hangul", 600, "euc_kr")]


def api(wiki, variant, params):
    params = dict(params, format="json")
    if variant:
        params["variant"] = variant
    url = f"https://{wiki}.wikipedia.org/w/api.php?" + urllib.parse.urlencode(params)
    for _ in range(5):
        try:
            return json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30))
        except Exception as e:  # noqa: BLE001 - retry any network error
            print(e, file=sys.stderr)
            time.sleep(3)
    return {}


def fetch(outdir, articles=400, intros=1500):
    os.makedirs(outdir, exist_ok=True)
    for key, (wiki, variant, seeds) in LOCALES.items():
        titles = []
        for seed in seeds:
            cont = {}
            while True:
                d = api(wiki, variant, dict(action="query", titles=seed, prop="links",
                                            plnamespace=0, pllimit="max", redirects=1, **cont))
                for p in d.get("query", {}).get("pages", {}).values():
                    titles += [l["title"] for l in p.get("links", [])]
                if "continue" not in d:
                    break
                cont = {"plcontinue": d["continue"]["plcontinue"]}
        titles = list(dict.fromkeys(seeds + titles))
        random.Random(1).shuffle(titles)
        with open(os.path.join(outdir, f"tech_{key}.txt"), "w", encoding="utf-8") as f:
            for t in titles[:articles]:
                d = api(wiki, variant, dict(action="query", titles=t, prop="extracts", explaintext=1, redirects=1))
                for p in d.get("query", {}).get("pages", {}).values():
                    if p.get("extract"):
                        f.write(p["extract"].replace("\n", " ") + "\n")
        with open(os.path.join(outdir, f"random_{key}.txt"), "w", encoding="utf-8") as f:
            got = 0
            while got < intros:
                d = api(wiki, variant, dict(action="query", generator="random", grnnamespace=0, grnlimit=20,
                                            prop="extracts", exintro=1, explaintext=1, exlimit=20))
                pages = d.get("query", {}).get("pages", {}).values()
                if not pages:
                    break
                for p in pages:
                    if p.get("extract"):
                        f.write(p["extract"].replace("\n", " ") + "\n")
                        got += 1


def keep(kind, c):
    o = ord(c)
    if kind == "hangul":
        return 0xAC00 <= o <= 0xD7A3
    return 0x4E00 <= o <= 0x9FFF or 0x3400 <= o <= 0x4DBF


def gen(outdir):
    out = ["""//! Top-N most frequent characters per CJK locale, used only to break ties
//! when a short legacy-encoded file decodes cleanly under several CJK
//! encodings (see `super::cjk_rescore`). Ordered by descending frequency.
//! Generated by `scripts/cjk-freq/gen_cjk_freq.py` from Astrolabe's own
//! character counts over a plain-text Wikipedia sample (zh with the zh-cn /
//! zh-tw variants, ja, ko). Only the top-N sets are kept: no text and no
//! third-party frequency table is reproduced.
"""]
    for name, key, kind, n, codec in SPEC:
        counts = collections.Counter()
        for path in glob.glob(os.path.join(outdir, f"*_{key}.txt")):
            with open(path, encoding="utf-8") as f:
                for line in f:
                    counts.update(c for c in line if keep(kind, c))
        picked = []
        for c, _ in counts.most_common():
            try:
                c.encode(codec)
            except UnicodeEncodeError:
                continue
            picked.append(c)
            if len(picked) == n:
                break
        assert len(picked) == n, (name, len(picked))
        total = sum(counts.values())
        print(f"{name}: {total} chars, {len(counts)} distinct, top {n} cover "
              f"{sum(counts[c] for c in picked) / total:.1%}", file=sys.stderr)
        s = "".join(picked)
        rows = "".join(f'    "{s[i:i + 50]}",\n' for i in range(0, len(s), 50))
        out.append(f"pub(super) const {name}: &str = concat!(\n{rows});\n")
    with open(DEST, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 3 or sys.argv[1] not in ("fetch", "gen"):
        sys.exit(__doc__)
    (fetch if sys.argv[1] == "fetch" else gen)(sys.argv[2])
